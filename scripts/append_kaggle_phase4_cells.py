        "    fin_wv = TfidfVectorizer(analyzer='word', ngram_range=(1, 2), sublinear_tf=True, dtype=np.float32)\n"
        "    X_fin = hstack([fin_cv.fit_transform(final_texts), fin_wv.fit_transform(final_texts)]).tocsr()\n"
        "    fin_ca = LogisticRegression(class_weight='balanced', max_iter=1000, random_state=SEED).fit(X_fin, final_lbl, sample_weight=final_weights)\n"
        "    fin_cb = OneVsRestClassifier(LogisticRegression(class_weight='balanced', max_iter=1000, random_state=SEED)).fit(X_fin, final_tech)\n"
        "    fin_cc = LogisticRegression(class_weight='balanced', max_iter=1000, random_state=SEED).fit(X_fin, final_act, sample_weight=final_weights)\n"
        "    with open(tfidf_final_cache, 'wb') as f:\n"
        "        pickle.dump({'cv': fin_cv, 'wv': fin_wv, 'ca': fin_ca, 'cb': fin_cb, 'cc': fin_cc}, f)\n"
