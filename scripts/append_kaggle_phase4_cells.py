        "test_xlmr_pa = np.vstack(xlmr_pa_chunks)\n"
        "test_xlmr_pb = np.vstack(xlmr_pb_chunks)\n"
        "test_xlmr_pc = np.vstack(xlmr_pc_chunks)\n"
        "print(f'XLM-R total inference time: {(time.time()-t_xlmr_all)/60:.2f} min')\n\n"
        "# 2. TF-IDF batched inference in 50k chunks (cached)\n"
        "tf_test_cache = os.path.join(WORK_DIR, 'test_tfidf_probs.npz')\n"
        "if os.path.isfile(tf_test_cache):\n"
        "    dtf = np.load(tf_test_cache)\n"
        "    test_tf_pa, test_tf_pb, test_tf_pc = dtf['pa'], dtf['pb'], dtf['pc']\n"
        "    print('Loaded cached TF-IDF test probabilities from', tf_test_cache)\n"
        "else:\n"
        "    t_tf_all = time.time()\n"
