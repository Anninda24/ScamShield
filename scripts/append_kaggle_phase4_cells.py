        "        eta_min = ((N_TEST - end) / rps) / 60.0\n"
        "        print(f'[TF-IDF] Chunk {start//CHUNK_SIZE + 1}: {end:,}/{N_TEST:,} | {rps:.1f} rows/s | ETA: {eta_min:.2f} min')\n"
        "    test_tf_pa = np.vstack(tf_pa_l)\n"
        "    test_tf_pb = np.vstack(tf_pb_l)\n"
        "    test_tf_pc = np.vstack(tf_pc_l)\n"
        "    np.savez(tf_test_cache, pa=test_tf_pa, pb=test_tf_pb, pc=test_tf_pc)\n"
