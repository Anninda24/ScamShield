import ast
import nbformat as nbf


def append_phase6_cells():
    nb_path = "kaggle_phase3.ipynb"
    with open(nb_path, "r", encoding="utf-8") as f:
        nb = nbf.read(f, as_version=4)

    new_cells = []

    new_cells.append(nbf.v4.new_markdown_cell(
        "---\n"
        "# Phase 6: Final Models on `synthetic_v3.csv` & `submission_v3.csv`\n"
        "- **Training Data:** `synthetic_v3.csv` (found recursively under `/kaggle/input`) + `300` noise-only rows + `86` real rows (clean & noisy copies at `5x` weight).\n"
        "- **Models:** Two 3-head `xlm-roberta-base` models (`seed=42` $\\rightarrow$ `xlmr_final_v3_s42.pt`, `seed=7` $\\rightarrow$ `xlmr_final_v3_s7.pt`) + `TF-IDF + LogisticRegression` (`tfidf_final_v3_models.pkl`).\n"
        "- **Thresholds & Calibration:** Reuses the Task B thresholds (`FINAL_TECH_THRESH`) and the Task A confidence calibrator (`calibrate_conf_v2`) chosen for `submission_v2.csv` (fit on held-out predictions from the v2-trained Split 2 models).\n"
        "- **Output:** `/kaggle/working/submission_v3.csv` (`submission_final.csv` and `submission_v2.csv` are untouched).\n"
    ))

    # Cell P6-1: Recursive search for synthetic_v3.csv, rebuild training set, free GPU, train s42, s7, and TF-IDF
    new_cells.append(nbf.v4.new_code_cell(
        "import gc\n"
        "import glob\n\n"
        "def free_gpu(*var_names):\n"
        "    for vn in var_names:\n"
        "        if vn in globals():\n"
        "            del globals()[vn]\n"
        "    gc.collect()\n"
        "    if torch.cuda.is_available():\n"
        "        torch.cuda.empty_cache()\n\n"
        "# Recursive search for synthetic_v3.csv under /kaggle/input\n"
        "v3_matches = sorted(glob.glob(os.path.join(INPUT_ROOT, '**', 'synthetic_v3.csv'), recursive=True))\n"
        "if not v3_matches:\n"
        "    raise FileNotFoundError(f'synthetic_v3.csv not found recursively under {INPUT_ROOT}. Contents: {os.listdir(INPUT_ROOT)}')\n"
        "V3_PATH = v3_matches[0]\n"
        "print('Found synthetic_v3.csv at:', V3_PATH)\n\n"
        "v3_df = pd.read_csv(V3_PATH, keep_default_na=False)\n"
        "v3_df['clean_text'] = v3_df['text'].fillna('').astype(str).apply(preprocess_text)\n"
        "v3_lbl = v3_df['label'].astype(int).values\n"
        "v3_tech = encode_techniques(v3_df['techniques'])\n"
        "v3_act = v3_df['action'].astype(int).values\n\n"
        "final_v3_texts = (\n"
        "    v3_df['clean_text'].tolist()\n"
        "    + noise_only_texts\n"
        "    + real_df['clean_text'].tolist()\n"
        "    + real_df['noisy_text'].tolist()\n"
        ")\n"
        "final_v3_lbl = np.concatenate([\n"
        "    v3_lbl,\n"
        "    np.zeros(n_noise, dtype=int),\n"
        "    real_lbl,\n"
        "    real_lbl,\n"
        "])\n"
        "final_v3_tech = np.vstack([\n"
        "    v3_tech,\n"
        "    np.zeros((n_noise, 6), dtype=int),\n"
        "    real_tech,\n"
        "    real_tech,\n"
        "])\n"
        "final_v3_act = np.concatenate([\n"
        "    v3_act,\n"
        "    np.zeros(n_noise, dtype=int),\n"
        "    real_act,\n"
        "    real_act,\n"
        "])\n"
        "final_v3_weights = np.concatenate([\n"
        "    np.ones(len(v3_df), dtype=np.float32),\n"
        "    np.ones(n_noise, dtype=np.float32),\n"
        "    np.full(len(real_df), 5.0, dtype=np.float32),\n"
        "    np.full(len(real_df), 5.0, dtype=np.float32),\n"
        "])\n"
        "print(f'Final v3 training set: {len(final_v3_texts):,} rows (synthetic_v3={len(v3_df):,}, noise_only={n_noise}, real_clean+noisy={2*len(real_df)} @ 5x)')\n\n"
        "TRAIN_ALPHA_VOCAB_V3 = set()\n"
        "for txt in final_v3_texts:\n"
        "    for tok in txt.split():\n"
        "        if tok not in ('[URL]', '[NUM]', '|||') and any(c.isalpha() for c in tok):\n"
        "            TRAIN_ALPHA_VOCAB_V3.add(tok.strip('.,!?:;\"\\'()[]{}'))\n\n"
        "# Free old GPU models before training v3 seed 42\n"
        "free_gpu('m_s2', 'm_s1', 'm_final', 'm_s2_s7', 'm_final_s7')\n"
        "seed_everything(42)\n"
        "xlmr_v3_s42_ckpt = os.path.join(WORK_DIR, 'xlmr_final_v3_s42.pt')\n"
        "m_v3_s42, tok_v3_s42 = train_three_head(\n"
        "    'XLM-R v3 (seed=42)', final_v3_texts, final_v3_lbl, final_v3_tech, final_v3_act,\n"
        "    final_v3_weights, xlmr_v3_s42_ckpt, model_name=BACKBONE, epochs=3, batch_size=32, lr=2e-5, max_len=256\n"
        ")\n\n"
        "# Free GPU before training v3 seed 7\n"
        "free_gpu('m_v3_s42')\n"
        "seed_everything(7)\n"
        "xlmr_v3_s7_ckpt = os.path.join(WORK_DIR, 'xlmr_final_v3_s7.pt')\n"
        "m_v3_s7, tok_v3_s7 = train_three_head(\n"
        "    'XLM-R v3 (seed=7)', final_v3_texts, final_v3_lbl, final_v3_tech, final_v3_act,\n"
        "    final_v3_weights, xlmr_v3_s7_ckpt, model_name=BACKBONE, epochs=3, batch_size=32, lr=2e-5, max_len=256\n"
        ")\n"
        "free_gpu('m_v3_s7')\n"
        "seed_everything(SEED)\n\n"
        "# Retrain TF-IDF on the exact same v3 final training set\n"
        "tfidf_v3_cache = os.path.join(WORK_DIR, 'tfidf_final_v3_models.pkl')\n"
        "if os.path.isfile(tfidf_v3_cache):\n"
        "    with open(tfidf_v3_cache, 'rb') as f:\n"
        "        tf3 = pickle.load(f)\n"
        "    v3_cv, v3_wv = tf3['cv'], tf3['wv']\n"
        "    v3_ca, v3_cb, v3_cc = tf3['ca'], tf3['cb'], tf3['cc']\n"
        "    print('Loaded cached final v3 TF-IDF models from', tfidf_v3_cache)\n"
        "else:\n"
        "    t_tf3 = time.time()\n"
        "    v3_cv = TfidfVectorizer(analyzer='char_wb', ngram_range=(2, 5), sublinear_tf=True, dtype=np.float32)\n"
        "    v3_wv = TfidfVectorizer(analyzer='word', ngram_range=(1, 2), sublinear_tf=True, dtype=np.float32)\n"
        "    X_v3 = hstack([v3_cv.fit_transform(final_v3_texts), v3_wv.fit_transform(final_v3_texts)]).tocsr()\n"
        "    v3_ca = LogisticRegression(class_weight='balanced', max_iter=1000, random_state=SEED).fit(X_v3, final_v3_lbl, sample_weight=final_v3_weights)\n"
        "    v3_cb = OneVsRestClassifier(LogisticRegression(class_weight='balanced', max_iter=1000, random_state=SEED)).fit(X_v3, final_v3_tech)\n"
        "    v3_cc = LogisticRegression(class_weight='balanced', max_iter=1000, random_state=SEED).fit(X_v3, final_v3_act, sample_weight=final_v3_weights)\n"
        "    with open(tfidf_v3_cache, 'wb') as f:\n"
        "        pickle.dump({'cv': v3_cv, 'wv': v3_wv, 'ca': v3_ca, 'cb': v3_cb, 'cc': v3_cc}, f)\n"
        "    print(f'Trained & cached final v3 TF-IDF models in {time.time()-t_tf3:.1f}s')\n"
    ))

    # Cell P6-2: Length-sorted FP16 test inference for both v3 XLM-R models + TF-IDF v3
    new_cells.append(nbf.v4.new_code_cell(
        "def run_xlmr_test_chunks(ckpt_path, tok, chunk_prefix, label_tag):\n"
        "    pa_l, pb_l, pc_l = [], [], []\n"
        "    mdl = None\n"
        "    t_all = time.time()\n"
        "    for start in range(0, N_TEST, CHUNK_SIZE):\n"
        "        end = min(start + CHUNK_SIZE, N_TEST)\n"
        "        c_idx = start // CHUNK_SIZE\n"
        "        c_file = os.path.join(WORK_DIR, f'{chunk_prefix}_{c_idx}.npz')\n"
        "        if os.path.isfile(c_file):\n"
        "            d = np.load(c_file)\n"
        "            pa_l.append(d['pa']); pb_l.append(d['pb']); pc_l.append(d['pc'])\n"
        "            print(f'[{label_tag}] Loaded cached chunk {c_idx+1} ({end:,}/{N_TEST:,})')\n"
        "            continue\n"
        "        if mdl is None:\n"
        "            mdl = ThreeHeadEncoder(BACKBONE).to(DEVICE)\n"
        "            mdl.load_state_dict(torch.load(ckpt_path, map_location=DEVICE))\n"
        "            mdl.eval()\n"
        "        t_c = time.time()\n"
        "        raw_slice = test_df['text'].iloc[start:end].fillna('').astype(str).apply(preprocess_text).tolist()\n"
        "        order = np.argsort([len(t) for t in raw_slice])\n"
        "        sorted_slice = [raw_slice[i] for i in order]\n"
        "        pa_s, pb_s, pc_s = predict_three_head(mdl, sorted_slice, tok, batch_size=256, max_len=256)\n"
        "        inv_order = np.argsort(order)\n"
        "        pa_c, pb_c, pc_c = pa_s[inv_order], pb_s[inv_order], pc_s[inv_order]\n"
        "        np.savez(c_file, pa=pa_c, pb=pb_c, pc=pc_c)\n"
        "        pa_l.append(pa_c); pb_l.append(pb_c); pc_l.append(pc_c)\n"
        "        dt = time.time() - t_c\n"
        "        rps = len(raw_slice) / dt\n"
        "        eta_min = ((N_TEST - end) / rps) / 60.0\n"
        "        print(f'[{label_tag}] Chunk {c_idx+1}: {end:,}/{N_TEST:,} | {rps:.1f} rows/s | ETA: {eta_min:.1f} min')\n"
        "    if mdl is not None:\n"
        "        del mdl\n"
        "        gc.collect()\n"
        "        if torch.cuda.is_available():\n"
        "            torch.cuda.empty_cache()\n"
        "    print(f'[{label_tag}] Total inference time: {(time.time()-t_all)/60:.2f} min')\n"
        "    return np.vstack(pa_l), np.vstack(pb_l), np.vstack(pc_l)\n\n"
        "v3_s42_pa, v3_s42_pb, v3_s42_pc = run_xlmr_test_chunks(xlmr_v3_s42_ckpt, tok_v3_s42, 'test_xlmr_v3_s42_chunk', 'XLM-R v3 s42')\n"
        "v3_s7_pa, v3_s7_pb, v3_s7_pc = run_xlmr_test_chunks(xlmr_v3_s7_ckpt, tok_v3_s7, 'test_xlmr_v3_s7_chunk', 'XLM-R v3 s7')\n\n"
        "tf3_test_cache = os.path.join(WORK_DIR, 'test_tfidf_v3_probs.npz')\n"
        "if os.path.isfile(tf3_test_cache):\n"
        "    dtf3 = np.load(tf3_test_cache)\n"
        "    test_tf3_pa, test_tf3_pb, test_tf3_pc = dtf3['pa'], dtf3['pb'], dtf3['pc']\n"
        "    print('Loaded cached TF-IDF v3 test probabilities from', tf3_test_cache)\n"
        "else:\n"
        "    tf3_pa_l, tf3_pb_l, tf3_pc_l = [], [], []\n"
        "    for start in range(0, N_TEST, CHUNK_SIZE):\n"
        "        end = min(start + CHUNK_SIZE, N_TEST)\n"
        "        clean_slice = test_df['text'].iloc[start:end].fillna('').astype(str).apply(preprocess_text).tolist()\n"
        "        X_t = hstack([v3_cv.transform(clean_slice), v3_wv.transform(clean_slice)]).tocsr()\n"
        "        tf3_pa_l.append(v3_ca.predict_proba(X_t).astype(np.float32))\n"
        "        tf3_pb_l.append(v3_cb.predict_proba(X_t).astype(np.float32))\n"
        "        tf3_pc_l.append(v3_cc.predict_proba(X_t).astype(np.float32))\n"
        "    test_tf3_pa, test_tf3_pb, test_tf3_pc = np.vstack(tf3_pa_l), np.vstack(tf3_pb_l), np.vstack(tf3_pc_l)\n"
        "    np.savez(tf3_test_cache, pa=test_tf3_pa, pb=test_tf3_pb, pc=test_tf3_pc)\n"
        "    print('Saved TF-IDF v3 test probabilities to', tf3_test_cache)\n"
    ))

    # Cell P6-3: Blend, Post-Process, Write submission_v3.csv, Validate, Compare vs submission_v2.csv & Top 20 Probability Changes
    new_cells.append(nbf.v4.new_code_cell(
        "xlmr_v3_mean_pa = 0.5 * (v3_s42_pa + v3_s7_pa)\n"
        "xlmr_v3_mean_pb = 0.5 * (v3_s42_pb + v3_s7_pb)\n"
        "xlmr_v3_mean_pc = 0.5 * (v3_s42_pc + v3_s7_pc)\n\n"
        "v3_pa = wA * xlmr_v3_mean_pa + (1.0 - wA) * test_tf3_pa\n"
        "v3_pb = wB * xlmr_v3_mean_pb + (1.0 - wB) * test_tf3_pb\n"
        "v3_pc = wC * xlmr_v3_mean_pc + (1.0 - wC) * test_tf3_pc\n\n"
        "v3_labels = np.argmax(v3_pa, axis=1)\n"
        "v3_actions = np.argmax(v3_pc, axis=1)\n"
        "v3_confs = calibrate_conf_v2(v3_pa)\n"
        "v3_techs = []\n"
        "v3_noise_hits = 0\n\n"
        "def is_oov_noise_only_v3(clean_txt: str) -> bool:\n"
        "    if '[URL]' in clean_txt or '[NUM]' in clean_txt:\n"
        "        return False\n"
        "    alpha_toks = [\n"
        "        tok.strip('.,!?:;\"\\'()[]{}')\n"
        "        for tok in clean_txt.split()\n"
        "        if tok != '|||' and any(c.isalpha() for c in tok)\n"
        "    ]\n"
        "    if not alpha_toks:\n"
        "        return False\n"
        "    return all(t not in TRAIN_ALPHA_VOCAB_V3 for t in alpha_toks)\n\n"
        "for i in range(N_TEST):\n"
        "    if is_oov_noise_only_v3(clean_all_test[i]):\n"
        "        v3_labels[i] = 0\n"
        "        v3_techs.append('NONE')\n"
        "        v3_actions[i] = 0\n"
        "        v3_confs[i] = 0.5\n"
        "        v3_noise_hits += 1\n"
        "        continue\n"
        "    lbl = int(v3_labels[i])\n"
        "    if lbl in (0, 5):\n"
        "        v3_techs.append('NONE')\n"
        "        v3_actions[i] = 0\n"
        "    else:\n"
        "        active = [TECH_CODES[j] for j in range(6) if v3_pb[i, j] >= FINAL_TECH_THRESH[j]]\n"
        "        if not active:\n"
        "            active = [TECH_CODES[int(np.argmax(v3_pb[i]))]]\n"
        "        v3_techs.append('|'.join(sorted(active)))\n\n"
        "sub_v3_path = os.path.join(WORK_DIR, 'submission_v3.csv')\n"
        "pd.DataFrame({\n"
        "    'id': test_df['id'].values.astype(int),\n"
        "    'label': v3_labels.astype(int),\n"
        "    'techniques': v3_techs,\n"
        "    'action': v3_actions.astype(int),\n"
        "    'confidence': v3_confs,\n"
        "}).to_csv(sub_v3_path, index=False)\n"
        "print(f'Wrote {sub_v3_path} ({N_TEST:,} rows, noise_hits={v3_noise_hits:,})')\n\n"
        "# Inline validator on submission_v3.csv\n"
        "v3_chk = pd.read_csv(sub_v3_path, keep_default_na=False)\n"
        "assert list(v3_chk.columns) == ['id', 'label', 'techniques', 'action', 'confidence'], 'Header mismatch'\n"
        "assert len(v3_chk) == N_TEST == len(ref_ids), 'Row count mismatch'\n"
        "assert (v3_chk['id'].astype(int).values == test_df['id'].values).all(), 'ID order mismatch'\n"
        "assert not v3_chk['id'].duplicated().any(), 'Duplicate IDs'\n"
        "for col in v3_chk.columns:\n"
        "    assert (v3_chk[col].astype(str).str.strip() != '').all(), f'Blank values in {col}'\n"
        "assert v3_chk['label'].astype(int).isin([0,1,2,3,4,5]).all(), 'Invalid label'\n"
        "assert v3_chk['action'].astype(int).isin([0,1,2,3,4,5]).all(), 'Invalid action'\n"
        "assert v3_chk['techniques'].apply(_chk_tech).all(), 'Invalid techniques'\n"
        "c_v3 = pd.to_numeric(v3_chk['confidence'], errors='raise')\n"
        "assert not c_v3.isna().any() and ((c_v3 >= 0.0) & (c_v3 <= 1.0)).all(), 'Invalid confidence'\n"
        "print('PASS: submission_v3.csv passed all validator checks!')\n\n"
        "# Compare with submission_v2.csv\n"
        "v2_chk_df = pd.read_csv(os.path.join(WORK_DIR, 'submission_v2.csv'), keep_default_na=False)\n"
        "v2_lbls_arr = v2_chk_df['label'].astype(int).values\n"
        "v3_lbls_arr = v3_chk['label'].astype(int).values\n"
        "changed_mask = v2_lbls_arr != v3_lbls_arr\n"
        "n_changed_v3 = int(changed_mask.sum())\n"
        "agree_v3 = (v2_lbls_arr == v3_lbls_arr).mean() * 100.0\n"
        "print(f'\\nLabel changes vs submission_v2.csv: {n_changed_v3:,} / {N_TEST:,} rows | Agreement rate: {agree_v3:.2f}%')\n\n"
        "print('\\nPredicted Label Distribution (submission_v3.csv vs submission_v2.csv):')\n"
        "vc3 = pd.Series(v3_lbls_arr).value_counts().sort_index()\n"
        "vc2 = pd.Series(v2_lbls_arr).value_counts().sort_index()\n"
        "for k in range(6):\n"
        "    c3, c2 = int(vc3.get(k, 0)), int(vc2.get(k, 0))\n"
        "    print(f'  Label {k}: v3={c3:7,d} ({c3/N_TEST*100:5.2f}%)  | v2={c2:7,d} ({c2/N_TEST*100:5.2f}%)')\n\n"
        "# 20 changed rows with the largest probability changes\n"
        "prob_deltas = np.max(np.abs(v3_pa - v2_pa), axis=1)\n"
        "changed_idx = np.where(changed_mask)[0]\n"
        "top20_changed = changed_idx[np.argsort(-prob_deltas[changed_idx])][:20]\n"
        "print('\\n=== 20 CHANGED ROWS WITH LARGEST PROBABILITY CHANGES (v2 -> v3) ===')\n"
        "for rank, idx in enumerate(top20_changed, 1):\n"
        "    short_txt = repr(str(test_df.loc[idx, 'text'])[:105])\n"
        "    print(f'[{rank:02d}] old={v2_lbls_arr[idx]} -> new={v3_lbls_arr[idx]} (max_delta={prob_deltas[idx]:.4f}) | {short_txt}')\n"
    ))

    nb["cells"].extend(new_cells)

    for c in nb["cells"]:
        if c["cell_type"] == "code":
            ast.parse(c["source"])

    with open(nb_path, "w", encoding="utf-8") as f:
        nbf.write(nb, f)
    print(f"Appended {len(new_cells)} Phase 6 cells to {nb_path} (total cells: {len(nb['cells'])}). All code cells syntax-checked.")


if __name__ == "__main__":
    append_phase6_cells()
