import ast
import nbformat as nbf


def append_phase5_cells():
    nb_path = "kaggle_phase3.ipynb"
    with open(nb_path, "r", encoding="utf-8") as f:
        nb = nbf.read(f, as_version=4)

    new_cells = []

    new_cells.append(nbf.v4.new_markdown_cell(
        "---\n"
        "# Phase 5: Multi-Seed XLM-R Ensemble, Task B Threshold Tuning & `submission_v2.csv`\n"
        "- **Second XLM-R (`seed=7`):** Trained on Split 2 (for 2-seed held-out check) and on the full final training set (`xlmr_final_seed7.pt`).\n"
        "- **Ensemble:** `XLM-R_mean = 0.5 * (XLM-R_seed42 + XLM-R_seed7)`, then blended with TF-IDF using Phase 4 weights `(wA, wB, wC)`.\n"
        "- **Task B Thresholds:** Tuned per technique (`0.30..0.70` step `0.05`) and shrunk 50% toward `0.5`; kept only if average Task B Macro F1 improves by `> 0.01` on BOTH Split 2 and Split 1 Fold 0.\n"
        "- **Output:** `/kaggle/working/submission_v2.csv` (`submission_final.csv` is untouched).\n"
    ))

    # Cell P5-1: Train Split 2 (seed=7) + Evaluate seed42 vs seed7 vs mean + Train Final (seed=7)
    new_cells.append(nbf.v4.new_code_cell(
        "seed_everything(7)\n\n"
        "# 1A. Split 2 (seed=7) to verify 2-seed averaging on 86 real rows\n"
        "xlmr_s2_s7_ckpt = os.path.join(WORK_DIR, 'xlmr_split2_seed7.pt')\n"
        "xlmr_s2_s7_preds = os.path.join(WORK_DIR, 'preds_xlmr_s2_seed7.npz')\n"
        "m_s2_s7, tok_s2_s7 = train_three_head(\n"
        "    'XLM-R Split2 (seed=7)', synth_df.loc[split2_train_idx, 'clean_text'].tolist(),\n"
        "    synth_lbl[split2_train_idx], synth_tech[split2_train_idx], synth_act[split2_train_idx],\n"
        "    np.ones(len(split2_train_idx)), xlmr_s2_s7_ckpt, model_name=BACKBONE\n"
        ")\n"
        "if os.path.isfile(xlmr_s2_s7_preds):\n"
        "    d_s7 = np.load(xlmr_s2_s7_preds)\n"
        "    s2_s7_c = (d_s7['pa_c'], d_s7['pb_c'], d_s7['pc_c'])\n"
        "    s2_s7_n = (d_s7['pa_n'], d_s7['pb_n'], d_s7['pc_n'])\n"
        "else:\n"
        "    pa_c7, pb_c7, pc_c7 = predict_three_head(m_s2_s7, real_df['clean_text'].tolist(), tok_s2_s7)\n"
        "    pa_n7, pb_n7, pc_n7 = predict_three_head(m_s2_s7, real_df['noisy_text'].tolist(), tok_s2_s7)\n"
        "    np.savez(xlmr_s2_s7_preds, pa_c=pa_c7, pb_c=pb_c7, pc_c=pc_c7, pa_n=pa_n7, pb_n=pb_n7, pc_n=pc_n7)\n"
        "    s2_s7_c, s2_s7_n = (pa_c7, pb_c7, pc_c7), (pa_n7, pb_n7, pc_n7)\n\n"
        "s2_mean_c = tuple(0.5 * (d_x2[f'{k}_c'] + s2_s7_c[idx]) for idx, k in enumerate(['pa', 'pb', 'pc']))\n"
        "s2_mean_n = tuple(0.5 * (d_x2[f'{k}_n'] + s2_s7_n[idx]) for idx, k in enumerate(['pa', 'pb', 'pc']))\n\n"
        "print('=== SPLIT 2 (86 REAL ROWS) COMPARISON: SEED 42 vs SEED 7 vs MEAN ===')\n"
        "for tag_m, tup_c, tup_n in [\n"
        "    ('Seed 42 alone', (d_x2['pa_c'], d_x2['pb_c'], d_x2['pc_c']), (d_x2['pa_n'], d_x2['pb_n'], d_x2['pc_n'])),\n"
        "    ('Seed 7  alone', s2_s7_c, s2_s7_n),\n"
        "    ('Mean (42 + 7)', s2_mean_c, s2_mean_n),\n"
        "]:\n"
        "    mc = eval_metrics(real_lbl, real_tech, real_act, np.argmax(tup_c[0], 1), tup_c[1], np.argmax(tup_c[2], 1), np.max(tup_c[0], 1))\n"
        "    mn = eval_metrics(real_lbl, real_tech, real_act, np.argmax(tup_n[0], 1), tup_n[1], np.argmax(tup_n[2], 1), np.max(tup_n[0], 1))\n"
        "    print(f'  {tag_m:14s} | CLEAN: A={mc[0]:.4f} B={mc[1]:.4f} C={mc[2]:.4f} | NOISY: A={mn[0]:.4f} B={mn[1]:.4f} C={mn[2]:.4f}')\n\n"
        "# 1B. Final XLM-R (seed=7) on full final training set\n"
        "xlmr_final_s7_ckpt = os.path.join(WORK_DIR, 'xlmr_final_seed7.pt')\n"
        "m_final_s7, tok_final_s7 = train_three_head(\n"
        "    'XLM-R Final (seed=7)', final_texts, final_lbl, final_tech, final_act,\n"
        "    final_weights, xlmr_final_s7_ckpt, model_name=BACKBONE, epochs=3, batch_size=32, lr=2e-5, max_len=256\n"
        ")\n"
        "seed_everything(SEED)\n"
    ))

    # Cell P5-2: Task B Threshold Tuning + Re-calibration on 2-Seed Blend
    new_cells.append(nbf.v4.new_code_cell(
        "# Task B blended held-out probabilities (using 2-seed XLM-R mean on Split 2, seed 42 on Split 1 F0)\n"
        "b_s2_c = wB * s2_mean_c[1] + (1.0 - wB) * d_tf['s2_pb_c']\n"
        "b_s2_n = wB * s2_mean_n[1] + (1.0 - wB) * d_tf['s2_pb_n']\n"
        "b_s1_c = wB * d_x1['pb_c'] + (1.0 - wB) * d_tf['s1_pb_c'][va_f0]\n"
        "b_s1_n = wB * d_x1['pb_n'] + (1.0 - wB) * d_tf['s1_pb_n'][va_f0]\n\n"
        "b_s2_all = np.vstack([b_s2_c, b_s2_n])\n"
        "y_s2_b_all = np.vstack([real_tech, real_tech])\n"
        "b_s1_all = np.vstack([b_s1_c, b_s1_n])\n"
        "y_s1_b_all = np.vstack([synth_tech[va_f0], synth_tech[va_f0]])\n"
        "b_ho_all = np.vstack([b_s2_all, b_s1_all])\n"
        "y_ho_b_all = np.vstack([y_s2_b_all, y_s1_b_all])\n\n"
        "grid_t = np.round(np.arange(0.30, 0.71, 0.05), 2)\n"
        "shrunk_thresh = np.full(6, 0.5, dtype=float)\n"
        "print('=== TASK B PER-TECHNIQUE THRESHOLD TUNING ===')\n"
        "for j, code in enumerate(TECH_CODES):\n"
        "    f1_before = f1_score(y_ho_b_all[:, j], (b_ho_all[:, j] >= 0.5).astype(int), zero_division=0)\n"
        "    best_t, best_f1 = 0.5, -1.0\n"
        "    for t in grid_t:\n"
        "        sc = f1_score(y_ho_b_all[:, j], (b_ho_all[:, j] >= t).astype(int), zero_division=0)\n"
        "        if sc > best_f1:\n"
        "            best_f1, best_t = sc, float(t)\n"
        "    t_shrunk = 0.5 + 0.5 * (best_t - 0.5)\n"
        "    shrunk_thresh[j] = t_shrunk\n"
        "    f1_after = f1_score(y_ho_b_all[:, j], (b_ho_all[:, j] >= t_shrunk).astype(int), zero_division=0)\n"
        "    print(f'  {code}: tuned={best_t:.2f} -> shrunk={t_shrunk:.3f} | F1_before={f1_before:.4f} -> F1_after={f1_after:.4f}')\n\n"
        "s2_b_before = float(np.mean([f1_score(y_s2_b_all[:, j], (b_s2_all[:, j] >= 0.5).astype(int), zero_division=0) for j in range(6)]))\n"
        "s2_b_after = float(np.mean([f1_score(y_s2_b_all[:, j], (b_s2_all[:, j] >= shrunk_thresh[j]).astype(int), zero_division=0) for j in range(6)]))\n"
        "s1_b_before = float(np.mean([f1_score(y_s1_b_all[:, j], (b_s1_all[:, j] >= 0.5).astype(int), zero_division=0) for j in range(6)]))\n"
        "s1_b_after = float(np.mean([f1_score(y_s1_b_all[:, j], (b_s1_all[:, j] >= shrunk_thresh[j]).astype(int), zero_division=0) for j in range(6)]))\n"
        "print(f'Split 2 Task B Macro F1: {s2_b_before:.4f} -> {s2_b_after:.4f} (diff={s2_b_after - s2_b_before:+.4f})')\n"
        "print(f'Split 1 Task B Macro F1: {s1_b_before:.4f} -> {s1_b_after:.4f} (diff={s1_b_after - s1_b_before:+.4f})')\n\n"
        "if (s2_b_after - s2_b_before > 0.01) and (s1_b_after - s1_b_before > 0.01):\n"
        "    FINAL_TECH_THRESH = shrunk_thresh\n"
        "    print('KEEPING tuned+shrunk thresholds:', np.round(FINAL_TECH_THRESH, 3))\n"
        "else:\n"
        "    FINAL_TECH_THRESH = np.full(6, 0.5, dtype=float)\n"
        "    print('REVERTING to 0.5 thresholds (improvement <= 0.01 on one or both held-out sets).')\n\n"
        "# Re-calibrate confidence on 2-seed blended held-out Task A probabilities\n"
        "ho_pa_v2 = np.vstack([\n"
        "    wA * s2_mean_c[0] + (1.0 - wA) * d_tf['s2_pa_c'],\n"
        "    wA * s2_mean_n[0] + (1.0 - wA) * d_tf['s2_pa_n'],\n"
        "    wA * d_x1['pa_c'] + (1.0 - wA) * d_tf['s1_pa_c'][va_f0],\n"
        "    wA * d_x1['pa_n'] + (1.0 - wA) * d_tf['s1_pa_n'][va_f0],\n"
        "])\n"
        "ho_pred_v2 = np.argmax(ho_pa_v2, axis=1)\n"
        "ho_corr_v2 = (ho_pred_v2 == ho_y_a).astype(int)\n"
        "ho_raw_v2 = np.max(ho_pa_v2, axis=1)\n\n"
        "brier_raw_v2 = brier_score_loss(ho_corr_v2, ho_raw_v2)\n"
        "log_ho_v2 = np.log(np.clip(ho_pa_v2, 1e-12, 1.0))\n"
        "def temp_nll_v2(T):\n"
        "    sc = log_ho_v2 / T\n"
        "    sc -= np.max(sc, axis=1, keepdims=True)\n"
        "    ex = np.exp(sc)\n"
        "    pr = ex / np.sum(ex, axis=1, keepdims=True)\n"
        "    return -np.mean(np.log(np.clip(pr[np.arange(len(ho_y_a)), ho_y_a], 1e-12, 1.0)))\n"
        "opt_T_v2 = float(minimize_scalar(temp_nll_v2, bounds=(0.2, 5.0), method='bounded').x)\n"
        "ho_temp_v2 = apply_temp(ho_pa_v2, opt_T_v2)\n"
        "brier_temp_v2 = brier_score_loss(ho_corr_v2, ho_temp_v2)\n\n"
        "iso_v2 = IsotonicRegression(y_min=0.05, y_max=0.98, out_of_bounds='clip').fit(ho_raw_v2, ho_corr_v2)\n"
        "brier_iso_v2 = brier_score_loss(ho_corr_v2, iso_v2.predict(ho_raw_v2))\n\n"
        "platt_v2 = LogisticRegression(C=1.0, max_iter=500, random_state=SEED).fit(ho_raw_v2.reshape(-1, 1), ho_corr_v2)\n"
        "brier_platt_v2 = brier_score_loss(ho_corr_v2, platt_v2.predict_proba(ho_raw_v2.reshape(-1, 1))[:, 1])\n\n"
        "cal_v2_scores = {'raw': brier_raw_v2, 'temperature': brier_temp_v2, 'isotonic': brier_iso_v2, 'platt': brier_platt_v2}\n"
        "best_cal_v2 = min(cal_v2_scores, key=cal_v2_scores.get)\n"
        "print('\\n=== PHASE 5 HELD-OUT BRIER SCORES ===')\n"
        "for k, v in cal_v2_scores.items():\n"
        "    print(f'  {k:12s}: {v:.5f}')\n"
        "print(f'Selected Phase 5 calibrator: {best_cal_v2} (opt_T={opt_T_v2:.3f})')\n\n"
        "def calibrate_conf_v2(probs_a):\n"
        "    raw_m = np.max(probs_a, axis=1)\n"
        "    if best_cal_v2 == 'raw':\n"
        "        c = raw_m\n"
        "    elif best_cal_v2 == 'temperature':\n"
        "        c = apply_temp(probs_a, opt_T_v2)\n"
        "    elif best_cal_v2 == 'isotonic':\n"
        "        c = iso_v2.predict(raw_m)\n"
        "    else:\n"
        "        c = platt_v2.predict_proba(raw_m.reshape(-1, 1))[:, 1]\n"
        "    return np.round(np.clip(c, 0.05, 0.98), 4)\n"
    ))

    # Cell P5-3: Test Inference with Seed-7 XLM-R, 2-Seed Blend, Post-Processing, Validate & Write submission_v2.csv
    new_cells.append(nbf.v4.new_code_cell(
        "m_final_s7.eval()\n"
        "t_s7_all = time.time()\n"
        "s7_pa_chunks, s7_pb_chunks, s7_pc_chunks = [], [], []\n"
        "for start in range(0, N_TEST, CHUNK_SIZE):\n"
        "    end = min(start + CHUNK_SIZE, N_TEST)\n"
        "    c_idx = start // CHUNK_SIZE\n"
        "    c_file = os.path.join(WORK_DIR, f'test_xlmr_s7_chunk_{c_idx}.npz')\n"
        "    if os.path.isfile(c_file):\n"
        "        d = np.load(c_file)\n"
        "        s7_pa_chunks.append(d['pa']); s7_pb_chunks.append(d['pb']); s7_pc_chunks.append(d['pc'])\n"
        "        print(f'[XLM-R seed=7] Loaded cached chunk {c_idx+1} ({end:,}/{N_TEST:,})')\n"
        "        continue\n"
        "    t_c = time.time()\n"
        "    raw_slice = test_df['text'].iloc[start:end].fillna('').astype(str).apply(preprocess_text).tolist()\n"
        "    order = np.argsort([len(t) for t in raw_slice])\n"
        "    sorted_slice = [raw_slice[i] for i in order]\n"
        "    pa_s, pb_s, pc_s = predict_three_head(m_final_s7, sorted_slice, tok_final_s7, batch_size=256, max_len=256)\n"
        "    inv_order = np.argsort(order)\n"
        "    pa_c, pb_c, pc_c = pa_s[inv_order], pb_s[inv_order], pc_s[inv_order]\n"
        "    np.savez(c_file, pa=pa_c, pb=pb_c, pc=pc_c)\n"
        "    s7_pa_chunks.append(pa_c); s7_pb_chunks.append(pb_c); s7_pc_chunks.append(pc_c)\n"
        "    dt = time.time() - t_c\n"
        "    rps = len(raw_slice) / dt\n"
        "    eta_min = ((N_TEST - end) / rps) / 60.0\n"
        "    print(f'[XLM-R seed=7] Chunk {c_idx+1}: {end:,}/{N_TEST:,} | {rps:.1f} rows/s | ETA: {eta_min:.1f} min')\n\n"
        "test_s7_pa = np.vstack(s7_pa_chunks)\n"
        "test_s7_pb = np.vstack(s7_pb_chunks)\n"
        "test_s7_pc = np.vstack(s7_pc_chunks)\n"
        "print(f'XLM-R seed=7 total inference time: {(time.time()-t_s7_all)/60:.2f} min')\n\n"
        "# Mean of the two XLM-R models, blended with TF-IDF\n"
        "xlmr_mean_pa = 0.5 * (test_xlmr_pa + test_s7_pa)\n"
        "xlmr_mean_pb = 0.5 * (test_xlmr_pb + test_s7_pb)\n"
        "xlmr_mean_pc = 0.5 * (test_xlmr_pc + test_s7_pc)\n\n"
        "v2_pa = wA * xlmr_mean_pa + (1.0 - wA) * test_tf_pa\n"
        "v2_pb = wB * xlmr_mean_pb + (1.0 - wB) * test_tf_pb\n"
        "v2_pc = wC * xlmr_mean_pc + (1.0 - wC) * test_tf_pc\n\n"
        "v2_labels = np.argmax(v2_pa, axis=1)\n"
        "v2_actions = np.argmax(v2_pc, axis=1)\n"
        "v2_confs = calibrate_conf_v2(v2_pa)\n"
        "v2_techs = []\n"
        "v2_noise_hits = 0\n\n"
        "for i in range(N_TEST):\n"
        "    if is_oov_noise_only(clean_all_test[i]):\n"
        "        v2_labels[i] = 0\n"
        "        v2_techs.append('NONE')\n"
        "        v2_actions[i] = 0\n"
        "        v2_confs[i] = 0.5\n"
        "        v2_noise_hits += 1\n"
        "        continue\n"
        "    lbl = int(v2_labels[i])\n"
        "    if lbl in (0, 5):\n"
        "        v2_techs.append('NONE')\n"
        "        v2_actions[i] = 0\n"
        "    else:\n"
        "        active = [TECH_CODES[j] for j in range(6) if v2_pb[i, j] >= FINAL_TECH_THRESH[j]]\n"
        "        if not active:\n"
        "            active = [TECH_CODES[int(np.argmax(v2_pb[i]))]]\n"
        "        v2_techs.append('|'.join(sorted(active)))\n\n"
        "sub_v2_path = os.path.join(WORK_DIR, 'submission_v2.csv')\n"
        "pd.DataFrame({\n"
        "    'id': test_df['id'].values.astype(int),\n"
        "    'label': v2_labels.astype(int),\n"
        "    'techniques': v2_techs,\n"
        "    'action': v2_actions.astype(int),\n"
        "    'confidence': v2_confs,\n"
        "}).to_csv(sub_v2_path, index=False)\n"
        "print(f'Wrote {sub_v2_path} ({N_TEST:,} rows, noise_hits={v2_noise_hits:,})')\n\n"
        "# Inline validator on submission_v2.csv\n"
        "v2_chk = pd.read_csv(sub_v2_path, keep_default_na=False)\n"
        "assert list(v2_chk.columns) == ['id', 'label', 'techniques', 'action', 'confidence'], 'Header mismatch'\n"
        "assert len(v2_chk) == N_TEST == len(ref_ids), 'Row count mismatch'\n"
        "assert (v2_chk['id'].astype(int).values == test_df['id'].values).all(), 'ID order mismatch'\n"
        "assert not v2_chk['id'].duplicated().any(), 'Duplicate IDs'\n"
        "for col in v2_chk.columns:\n"
        "    assert (v2_chk[col].astype(str).str.strip() != '').all(), f'Blank values in {col}'\n"
        "assert v2_chk['label'].astype(int).isin([0,1,2,3,4,5]).all(), 'Invalid label'\n"
        "assert v2_chk['action'].astype(int).isin([0,1,2,3,4,5]).all(), 'Invalid action'\n"
        "assert v2_chk['techniques'].apply(_chk_tech).all(), 'Invalid techniques'\n"
        "c_v2 = pd.to_numeric(v2_chk['confidence'], errors='raise')\n"
        "assert not c_v2.isna().any() and ((c_v2 >= 0.0) & (c_v2 <= 1.0)).all(), 'Invalid confidence'\n"
        "print('PASS: submission_v2.csv passed all validator checks!')\n\n"
        "# Compare with submission_final.csv\n"
        "fin_chk = pd.read_csv(sub_final_path, keep_default_na=False)\n"
        "fin_lbls = fin_chk['label'].astype(int).values\n"
        "v2_lbls = v2_chk['label'].astype(int).values\n"
        "n_changed = int((fin_lbls != v2_lbls).sum())\n"
        "agree_rate = (fin_lbls == v2_lbls).mean() * 100.0\n"
        "print(f'\\nLabel changes vs submission_final.csv: {n_changed:,} / {N_TEST:,} rows | Agreement rate: {agree_rate:.2f}%')\n\n"
        "print('\\nPredicted Label Distribution (submission_v2.csv vs submission_final.csv):')\n"
        "vc_v2 = pd.Series(v2_lbls).value_counts().sort_index()\n"
        "vc_fn = pd.Series(fin_lbls).value_counts().sort_index()\n"
        "for k in range(6):\n"
        "    c2, cf = int(vc_v2.get(k, 0)), int(vc_fn.get(k, 0))\n"
        "    print(f'  Label {k}: v2={c2:7,d} ({c2/N_TEST*100:5.2f}%)  | final={cf:7,d} ({cf/N_TEST*100:5.2f}%)')\n\n"
        "print('\\nFiles in /kaggle/working:')\n"
        "for fn in sorted(os.listdir(WORK_DIR)):\n"
        "    print(' ', fn)\n"
    ))

    nb["cells"].extend(new_cells)

    for c in nb["cells"]:
        if c["cell_type"] == "code":
            ast.parse(c["source"])

    with open(nb_path, "w", encoding="utf-8") as f:
        nbf.write(nb, f)
    print(f"Appended {len(new_cells)} Phase 5 cells to {nb_path} (total cells: {len(nb['cells'])}). All code cells syntax-checked.")


if __name__ == "__main__":
    append_phase5_cells()
